def parse_args():
    """Parse command-line arguments for ScenarioMIP biomass burning emission
    interpolation.

    Returns:
        argparse.Namespace: Parsed CLI arguments containing path, config,
            ext, scenario, and save filename parameters.
    """
    parser = ArgumentParser(
        prog="cmip7_SM_Bio_interpolate",
        description=(
            "Generate input files from CMIP7 ScenarioMIP biomass forcings"
        ),
        parents=[path_parser(), grid_parser(), config_parser(), ext_parser()],
    )
    parser.add_argument("--scenario")
    parser.add_argument("--save-filename")
    return parser.parse_args()


def _biomass_variable(species):
    """Format the ScenarioMIP biomass burning open-burning variable name.

    Args:
        species (str): Aerosol species name ('BC' or 'OC').

    Returns:
        str: Variable name (e.g. 'BC_em_openburning').
    """
    return f"{species}_em_openburning"


force_load = True


def split_sm_low_high(bc_cube, oc_cube, sector_dict):
    """Based on code generated by Gemini Flash 3.5.

    Slices and sums the 4D ScenarioMIP BC and OC emission cubes to partition
    low-level and high-level injection height emissions.

    Dimensions of input cubes: (time, sector, lat, lon)
    Sectors:
    0: Agricultural Waste Burning;
    1: Forest Burning;
    2: Grassland Burning;
    3: Peat Burning

    Args:
        bc_cube (iris.cube.Cube): 4D Black Carbon emissions cube.
        oc_cube (iris.cube.Cube): 4D Organic Carbon emissions cube.
        sector_dict (dict): Dictionary mapping sector names to integer indices.

    Returns:
        tuple of (iris.cube.Cube, iris.cube.Cube): (low, high) bulk aerosol
            emission cubes.
    """
    agri = sector_dict["Agricultural Waste Burning"]
    fore = sector_dict["Forest Burning"]
    sava = sector_dict["Grassland Burning"]
    peat = sector_dict["Peat Burning"]

    # Sum low-level sectors using collapsed:
    low_sectors = [agri, sava, peat]
    bc_low = bc_cube[:, low_sectors].collapsed("sector", iris.analysis.SUM)
    oc_low = oc_cube[:, low_sectors].collapsed("sector", iris.analysis.SUM)

    # Extract high-level sector:
    bc_high = bc_cube[:, fore]
    oc_high = oc_cube[:, fore]

    # Remove the scalar sector coordinate from the sliced cubes to prevent
    # coordinate mismatch warnings when summing or saving
    for cube in (bc_low, oc_low, bc_high, oc_high):
        if cube.coords("sector"):
            cube.remove_coord("sector")

    # Combine the species into bulk low and high emission cubes
    low = bc_low + oc_low
    high = bc_high + oc_high

    return low, high


def save_cmip7_sm_aerosol_biomass(args, load_fn, sector_dataset, save_dirpath):
    """Partition ScenarioMIP biomass emissions into low/high injection heights,
    regrid, and save.

    Partitions BC and OC by sector, sets coordinate systems, regrids
    horizontally to model grid,
    zeroes polar rows, attaches STASH item 130 (low) and 131 (high), and writes
    ancillary file.

    Args:
        args (argparse.Namespace): Command-line arguments.
        load_fn (callable): Callback that loads species cubes given the
            species name.
        sector_dataset (os.PathLike): Dataset of a source file whose sector
            attribute defines the fire sector indices.
        save_dirpath (pathlib.Path): Target directory for ancillary file.
    """
    bc = load_fn("BC")
    oc = load_fn("OC")

    # Iris doesn't read the sector coordinate
    sector_dict = load_sector_dict(sector_dataset)

    low, high = split_sm_low_high(bc, oc, sector_dict)

    if force_load:
        _ = low.data
        _ = high.data
        now = datetime.now()
        print(f"{now}: LO, HI done")

    # Regrid requires matching coordinate systems
    set_coord_system(low)
    set_coord_system(high)

    now = datetime.now()
    print(f"{now}: set_coord_system done")

    esm_grid_mask = esm_grid_mask_cube(args)
    low_esm = low.regrid(esm_grid_mask, INTERPOLATION_SCHEME)
    high_esm = high.regrid(esm_grid_mask, INTERPOLATION_SCHEME)

    now = datetime.now()
    print(f"{now}: regrid done")

    zero_poles(low_esm)
    zero_poles(high_esm)

    now = datetime.now()
    print(f"{now}: zero_poles done")

    low_esm.attributes["STASH"] = iris.fileformats.pp.STASH(
        model=1, section=0, item=130
    )
    high_esm.attributes["STASH"] = iris.fileformats.pp.STASH(
        model=1, section=0, item=131
    )

    save_ancil([low_esm, high_esm], save_dirpath, args.save_filename)

    now = datetime.now()
    print(f"{now}: save_ancil done")


def load_cmip7_sm_aerosol_biomass(args, config, ext_config, species):
    """Load, optionally extend beyond 2100, interpolate monthly, and extend
    time boundaries.

    Args:
        args (argparse.Namespace): Command-line arguments.
        config (dataset.DatasetConfig): Configuration of the open-burning
            emissions dataset.
        ext_config (dataset.DatasetConfig or None): Configuration of the
            open-burning emissions extension dataset, or None.
        species (str): Aerosol species name ('BC' or 'OC').

    Returns:
        iris.cube.Cube: Processed monthly biomass emissions cube.
    """
    # This data is missing over oceans,
    # so needs to be filled with zero for the model
    cube = load_cmip7_sm_aerosol_series(
        args,
        config,
        ext_config,
        _biomass_variable(species),
        fill_masked=True,
    )
    interpolated = interpolate_monthly(
        cube, CMIP7_SM_BEG_YEAR, sm_target_end_year(args)
    )
    return extend_years(interpolated)


